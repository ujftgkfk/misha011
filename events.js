// Получение событий для текущей недели
function getEventForWeek(week) {
    const month = Math.ceil(week / 4);
    const monthKey = `month_${month}`;

    if (EVENTS_DATABASE[monthKey]) {
        const events = EVENTS_DATABASE[monthKey];
        return events.find(e => e.week === week) || events[0];
    }

    return null;
}

// Проверка случайного события
function checkRandomEvent(gameState) {
    for (const event of RANDOM_EVENTS) {
        if (Math.random() < event.probability) {
            // Проверка условий
            if (event.minHealth && gameState.health < event.minHealth) {
                continue;
            }
            return event;
        }
    }
    return null;
}
